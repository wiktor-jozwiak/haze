#!/usr/bin/env python3
"""Generate crates/katana-core/src/map_gen.rs from BOSS TONE STUDIO (KATANA MkII) data.

Usage: gen_params.py <bts_html_dir> > crates/katana-core/src/map_gen.rs

<bts_html_dir> is the `html` directory unpacked from BTS `tmp.zip`
(…/AppData/Local/Roland/BOSS TONE STUDIO for KATANA MkII/tmp.zip).
Reads js/config/address_map.js (addresses, ranges) and export/{item.json,layout.div}
(value labels for select boxes). Output is a static table: no runtime parsing.
"""
import json
import re
import sys
from html.parser import HTMLParser

root = sys.argv[1]
amap = open(f"{root}/js/config/address_map.js", encoding="utf-8-sig").read()

# --- param arrays -----------------------------------------------------------
arrays = {}
for m in re.finditer(r"var (prm_prop_\w+) = \[(.*?)\n\s*\];", amap, re.S):
    entries = []
    for e in re.finditer(r"\{ addr:(0x[0-9a-fA-F]+), size:([^,]+?)\s*, ofs:(-?\d+)\s*, init:([^,]+?)\s*, min:(-?\d+)\s*, max:(-?\d+)\s*, name:'([^']*)'\s*\},\s*(?://\s*(PRM_\w+))?", m.group(2)):
        addr, size, ofs, init, mn, mx, name, prm = e.groups()
        try:
            init = int(init)
        except ValueError:
            init = 0
        entries.append(dict(addr=int(addr, 16), size=size.strip(), ofs=int(ofs), init=init, min=int(mn), max=int(mx), name=name.strip(), prm=prm or ""))
    arrays[m.group(1)] = entries

patch_blocks = re.search(r"var Patch = \[(.*?)\n\s*\];", amap, re.S).group(1)
blocks = [(int(a, 16), c, n) for a, c, n in re.findall(r"addr: (0x[0-9A-Fa-f]+), size: 0, child: (prm_prop_\w+),\s*name: '([^']+)'", patch_blocks)]


def nibble(x):
    return ((x & 0x7f000000) >> 3) | ((x & 0x007f0000) >> 2) | ((x & 0x00007f00) >> 1) | (x & 0x7f)


def width(size):
    if size.startswith("INTEGER1x"):
        return 1, "K::I7"
    if size == "INTEGER2x7":
        return 2, "K::I14"
    if size == "16":
        return 16, "K::Text"
    m = re.match(r"\(PADDING \| (0x[0-9a-fA-F]+)\)", size)
    if m:
        return int(m.group(1), 16), None
    raise SystemExit(f"unknown size {size}")


# --- labels from BTS layout ---------------------------------------------------
items = json.load(open(f"{root}/export/item.json", encoding="utf-8-sig"))


class P(HTMLParser):
    def __init__(s):
        super().__init__()
        s.stack, s.res = [], {}

    def handle_starttag(s, t, a):
        i = dict(a).get("id")
        s.stack.append(i)
        if i in items and "pid" in items[i] and i.endswith("select-box"):
            s.res.setdefault(i, [])

    def handle_endtag(s, t):
        if s.stack:
            s.stack.pop()

    def handle_data(s, d):
        d = d.strip()
        if not d:
            return
        for i in reversed(s.stack):
            if i in s.res:
                s.res[i].append(d)
                return


p = P()
p.feed(open(f"{root}/export/layout.div", encoding="utf-8-sig").read())
labels = {}  # (array, idx) -> [(value, label)]
block_array = {n: c for _, c, n in blocks}
for iid, texts in p.res.items():
    pid = items[iid]["pid"]
    parts = pid.split("%")
    if len(parts) != 3 or parts[0] != "Temporary" or parts[1] not in block_array:
        continue
    opts = texts[1:]  # first <p> mirrors current value
    if len(opts) < 2:
        continue
    order = items[iid].get("list_order") or list(range(len(opts)))
    if len(order) != len(opts):
        continue
    # BTS item pids address params by linear byte offset inside the block (not array index)
    key = (block_array[parts[1]], int(parts[2]))
    pairs = sorted(zip(order, opts))
    if key not in labels or len(pairs) > len(labels[key]):
        labels[key] = pairs

# --- emit ---------------------------------------------------------------------
out = []
w = out.append
w("// @generated by tools/gen_params.py from BOSS TONE STUDIO for KATANA MkII 2.1.0 — do not edit.")
w("use crate::map::{BlockDef, ParamDef, ParamKind as K};\n")
used_arrays = sorted({c for _, c, _ in blocks})
for arr in used_arrays:
    w(f"static {arr.upper()}: &[ParamDef] = &[")
    for idx, e in enumerate(arrays[arr]):
        nbytes, kind = width(e["size"])
        if kind is None:
            continue
        lab = labels.get((arr, nibble(e["addr"])), [])
        span = e["max"] - e["min"] + 1
        if lab and (len(lab) * 2 < span or any(not (e["min"] <= v <= e["max"]) for v, _ in lab)):
            lab = []  # does not describe this param
        lab_s = ", ".join(f"({v}, {json.dumps(t)})" for v, t in lab)
        w(f"    ParamDef {{ name: {json.dumps(e['name'])}, idx: {idx}, off: {nibble(e['addr'])}, kind: {kind}, ofs: {e['ofs']}, init: {e['init']}, prm: {json.dumps(e['prm'])}, min: {e['min']}, max: {e['max']}, labels: &[{lab_s}] }},")
    w("];")


def block_len(arr):
    last = arrays[arr][-1]
    return nibble(last["addr"]) + width(last["size"])[0]


w("\n/// Patch blocks, in BTS librarian order. `addr` is the linear offset inside a patch area.")
w("pub static PATCH_BLOCKS: &[BlockDef] = &[")
for addr, arr, name in blocks:
    w(f"    BlockDef {{ key: {json.dumps(name)}, addr: {nibble(addr)}, len: {block_len(arr)}, params: {arr.upper()} }},")
w("];")
print("\n".join(out))
